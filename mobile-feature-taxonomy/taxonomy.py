"""Readable L1/L2 list of the Firefox Mobile feature taxonomy, generated from features.yml.

Whether a feature exists on a platform is not maintained by hand: a feature is shown for iOS or
Android when that platform's feature-map.yml assigns any code to it.

FEATURES.md is generated, never edited by hand. The unit tests fail when it is out of sync with
features.yml or the maps; `feature_map.py drift --apply` regenerates it.

Usage:
    uv run taxonomy.py              # rewrite FEATURES.md
    uv run taxonomy.py --check      # exit 1 if FEATURES.md is out of date
    uv run taxonomy.py --csv        # print the list as CSV (e.g. to import into a spreadsheet)
"""

import argparse
import csv
import io
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
FEATURES_YML = os.path.join(HERE, "features.yml")
FEATURES_MD = os.path.join(HERE, "FEATURES.md")
PLATFORMS = ("ios", "android")
CSV_COLUMNS = ["l1_id", "l1_area", "l2_id", "l2_name", "ios", "android"]


def load(path=FEATURES_YML):
    with open(path) as f:
        return yaml.safe_load(f)


def mapped_features(platform):
    """IDs that <platform>/feature-map.yml assigns code to (file or symbol rules)."""
    with open(os.path.join(HERE, platform, "feature-map.yml")) as f:
        rules = yaml.safe_load(f)["rules"]
    return {r["feature"] for r in rules} | {s["feature"] for r in rules for s in r.get("symbols", [])}


def all_mapped():
    return {p: mapped_features(p) for p in PLATFORMS}


def areas(data):
    """[(l1_id, area_name, [feature])] in features.yml order."""
    out, index = [], {}
    for f in data["features"]:
        l1 = f["id"].split(".")[0]
        if l1 not in index:
            index[l1] = len(out)
            out.append((l1, f["area"], []))
        out[index[l1]][2].append(f)
    return out


def rows(data, mapped=None):
    mapped = all_mapped() if mapped is None else mapped
    for l1, area, features in areas(data):
        for f in features:
            yield {"l1_id": l1, "l1_area": area, "l2_id": f["id"], "l2_name": f["name"],
                   **{p: "yes" if f["id"] in mapped[p] else "no" for p in PLATFORMS}}


def to_csv(data, mapped=None):
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=CSV_COLUMNS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows(data, mapped))
    return buf.getvalue()


def to_markdown(data, mapped=None):
    mapped = all_mapped() if mapped is None else mapped
    groups = areas(data)
    total = sum(len(fs) for _, _, fs in groups)
    mark = lambda f, p: "✓" if f["id"] in mapped[p] else "—"
    out = [
        "<!-- Generated by taxonomy.py from features.yml and the feature maps. Do not edit by hand: run",
        "     `uv run taxonomy.py`. The unit tests fail if this file is out of sync. -->",
        "",
        "# Firefox Mobile feature taxonomy",
        "",
        f"{len(groups)} areas (L1) and {total} features (L2), shared by iOS and Android. Code, TestRail cases and bugs",
        "are attributed to the L2 ID; L1 is the first part of the ID. An L1 ID alone (e.g. `CRED`) is allowed for code",
        "that serves the whole area. ✓ means that platform's feature map assigns code to the feature; — means no code",
        "is mapped to it there (yet).",
        "",
        "## Areas",
        "",
        "| L1 | Area | Features |",
        "|---|---|---|",
    ]
    out += [f"| `{l1}` | [{area}](#{anchor(l1, area)}) | {len(fs)} |" for l1, area, fs in groups]
    out.append("")
    for l1, area, features in groups:
        out += [f"## {l1}: {area}", "", "| L2 ID | Feature | iOS | Android |", "|---|---|:-:|:-:|"]
        out += [f"| `{f['id']}` | {f['name']} | {mark(f, 'ios')} | {mark(f, 'android')} |" for f in features]
        out.append("")
    out += ["## Not product features", "",
            "Code that serves many features goes to a shared bucket, reported separately so it stays visible. "
            "Code that isn't counted at all is excluded.", "",
            "| ID | Covers |", "|---|---|"]
    out += [f"| `{s['id']}` | {s['name']} |" for s in data.get("shared", []) + data.get("excluded", [])]
    out.append("")
    return "\n".join(out)


def anchor(l1, area):
    """GitHub's heading anchor for '## L1: Area'."""
    text = f"{l1}: {area}".lower()
    return "".join(c for c in text if c.isalnum() or c in " -_").replace(" ", "-")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="exit 1 if FEATURES.md is out of date")
    group.add_argument("--csv", action="store_true", help="print the L1/L2 list as CSV")
    args = parser.parse_args(argv)
    data = load()
    if args.csv:
        sys.stdout.write(to_csv(data))
        return 0
    expected = to_markdown(data)
    current = open(FEATURES_MD).read() if os.path.exists(FEATURES_MD) else ""
    if args.check:
        if current != expected:
            print("FEATURES.md is out of date with features.yml or the maps. "
                  "Run: uv run mobile-feature-taxonomy/taxonomy.py",
                  file=sys.stderr)
            return 1
        return 0
    if current != expected:
        with open(FEATURES_MD, "w") as f:
            f.write(expected)
        print("FEATURES.md updated", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
